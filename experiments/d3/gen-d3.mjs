// Generate suites/d3/suite.yaml: four cells at the Dev role's difficulty D3 (symptom and
// goal as input; causes in CI logs, production log copies, platform documents and history;
// a design choice or a platform constraint in the fix). Contents: experiments/d3/cells.mjs.
// Output is JSON, which is valid YAML. Usage: node experiments/d3/gen-d3.mjs [out]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { cells } from './cells.mjs';

const out = process.argv[2] ?? 'suites/d3/suite.yaml';
const suite = {
  name: 'd3',
  subject: { path: '../../subjects/dev-structure/M' },
  repo_root: '../..',
  model: 'claude-sonnet-5-5',
  arms: ['script:null', 'script:reference', 'script:shortcut', 'script:escalate', 'script:harmful'],
  compare: { baseline: 'script:null', candidates: ['script:reference'] },
  cases: cells,
};
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `# Generated by experiments/d3/gen-d3.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
console.log(`wrote ${out}`);
