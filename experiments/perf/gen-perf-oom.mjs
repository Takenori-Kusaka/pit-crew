// A one-case suite for the per-container memory limit check (research-eval-parallelism §4, test 5):
// the "harmful" script holds about 700 MiB in memory before writing its answer. Run with
// PITWALL_ADMISSION=1 PITWALL_MEM_LIMIT_MIB=256 it should be OOM-killed and recorded as not a
// valid trial (neither a pass nor the agent's failure); reference must pass.
// Usage: node experiments/perf/gen-perf-oom.mjs [out]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const out = process.argv[2] ?? 'suites/perf-oom/suite.yaml';
const src = JSON.parse(readFileSync('suites/preflight-v1/suite.yaml', 'utf8').replace(/^#.*\n/, ''));
const base = src.cases[0];
const kase = {
  ...base,
  id: 'perf-oom',
  params: {
    ...base.params,
    request: 'answer.txt に ok と書いてください。',
    expect: { task: { name: 'task', check: 'grep -q -x ok answer.txt' }, conventions: [] },
    scripts: {
      null: 'true',
      reference: 'echo ok > answer.txt',
      harmful: 'head -c 700M /dev/zero | tail -n 1 > /dev/null && echo ok > answer.txt',
    },
    script_expect: { null: 'task-failed', reference: 'all-followed', harmful: 'all-followed' },
  },
};
const suite = { ...src, name: 'perf-oom', cases: [kase] };
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `# Generated by experiments/perf/gen-perf-oom.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
console.log(`wrote ${out}`);
