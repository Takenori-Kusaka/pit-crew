// Generate suites/jobsel/suite.yaml: six job-selection cells for the Dev role (deliverable 1.2),
// three minimal pairs. Contents: experiments/jobsel/cells.mjs. Output is JSON, which is valid YAML.
// Usage: node experiments/jobsel/gen-jobsel.mjs [out]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { cells } from './cells.mjs';

const out = process.argv[2] ?? 'suites/jobsel/suite.yaml';
const CONTROLS = ['null', 'correct', 'always-route', 'never-route', 'overreach', 'heavy', 'light'];
const suite = {
  name: 'jobsel',
  subject: { path: '../../subjects/dev-structure/M' },
  repo_root: '../..',
  model: 'claude-sonnet-5-5',
  arms: CONTROLS.map((s) => `script:${s}`),
  compare: { baseline: 'script:null', candidates: ['script:correct'] },
  cases: cells,
};
for (const c of cells) for (const s of CONTROLS) if (!c.params.scripts[s] || !c.params.script_expect[s]) throw new Error(`${c.id}: control ${s} missing`);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `# Generated by experiments/jobsel/gen-jobsel.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
console.log(`wrote ${out}`);
