// Generate suites/q2/suite.yaml: three Q2 cells (citation grounding, design 23 §3.2) in a
// repository too large to print at once. Contents: experiments/q2/cells.mjs.
// Output is JSON, which is valid YAML. Usage: node experiments/q2/gen-q2.mjs [out]
import { mkdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { buildCells } from './cells.mjs';

const out = process.argv[2] ?? 'suites/q2/suite.yaml';
const cells = buildCells();
const suite = {
  name: 'q2',
  subject: { path: '../../subjects/dev-structure/M' },
  repo_root: '../..',
  model: 'claude-sonnet-5-5',
  arms: ['script:null', 'script:reference', 'script:fabricated', 'script:nonexistent', 'script:partial'],
  compare: { baseline: 'script:null', candidates: ['script:reference'] },
  cases: cells,
};
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `# Generated by experiments/q2/gen-q2.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
const bytes = statSync(out).size;
const LIMIT = 3 * 1024 * 1024;
console.log(`wrote ${out}: ${cells.length} cells, ${cells.map((c) => c.params.history.length).join('/')} commits, ${(bytes / 1024).toFixed(0)} KB${bytes > LIMIT ? ' OVER 3 MB' : ''}`);
if (bytes > LIMIT) process.exit(1);
