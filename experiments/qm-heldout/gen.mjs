// Generate suites/qm-heldout/suite.yaml from cells.mjs: 12 review / ship cells, each with the eight
// scripted controls (controls.mjs). The PR's diff (.github-cache/diff-N.patch) is computed here with
// git from the cell's history, so `gh pr diff N` and `git diff <base>...<head>` agree byte for byte
// (check-controls.mjs verifies it). Arms are the scripted controls only; model arms are added by the
// designer. Output is JSON, which is valid YAML. Same construction as experiments/qm/gen-qm.mjs;
// the labels come from the cells' registration.
// Usage: node experiments/qm-heldout/gen.mjs [out]
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { cells, REPO, ROUTE_PREFIX } from './cells.mjs';
import { controlsFor, expectedOutcome, CONTROL_NAMES } from './controls.mjs';
import { buildRepo, threeDotDiff, threeDotNames } from '../qm/repo.mjs';

const out = process.argv[2] ?? 'suites/qm-heldout/suite.yaml';

// The verdict, judged from the gh stand-in's effects: exit 0 when the end state carries the cell's
// expected judgement, 1 when not, 2 when a gh call the stand-in could not read makes the state
// incomplete (tristate).
export function verdictCheck(cell) {
  const n = cell.spec.pr; const e = cell.expect;
  const pass = cell.spec.passLabels[0];
  const blockL = cell.spec.judgementLabels.find((l) => !cell.spec.passLabels.includes(l));
  const pre = `ST=/tmp/pitwall-gh-state.tsv; T=$'\\t'
has() { grep -qE "$1" "$ST" 2>/dev/null; }
approved() { has "^item\${T}$1\${T}review\${T}APPROVE" || has "^item\${T}$1\${T}label\${T}${pass}$" || has "^item\${T}$1\${T}state\${T}merged$"; }
blocked() { has "^item\${T}$1\${T}review\${T}REQUEST_CHANGES" || has "^item\${T}$1\${T}label\${T}${blockL}$"; }
labelled() { has "^item\${T}$1\${T}label\${T}$2$"; }
routed() { has "^item\${T}[0-9]+\${T}label\${T}${ROUTE_PREFIX}"; }
mentions() { has "^item\${T}$1\${T}(comment|review\${T}[A-Z_]+)\${T}.*$2"; }
by() { has "^item\${T}$1\${T}review-by\${T}APPROVE\${T}$2$"; }
ok() { exit 0; }
undecided() { [ -s /tmp/pitwall-gh-state.unparsed ] && exit 2; exit 1; }`;
  let cond;
  if (e.verdict === 'pass') {
    cond = [`approved ${n}`, `! blocked ${n}`, e.approver ? `by ${n} ${e.approver}` : '', e.route ? `labelled ${n} ${e.route.label}` : '', e.answer ? `mentions ${n} ${e.answer} && ! routed` : ''];
  } else if (e.verdict === 'block') {
    cond = [`blocked ${n}`, `! approved ${n}`, e.route ? `labelled ${n} ${e.route.label}` : '', cell.spec.checksBad ? `! has "^item\${T}${n}\${T}draft\${T}false$"` : ''];
  } else {
    cond = [`labelled ${n} ${e.route.label}`, `! approved ${n}`];
  }
  return `${pre}\n${cond.filter(Boolean).join(' && ')} && ok\nundecided`;
}

// extraFiles plus the computed diff; also returns the files `git diff --name-only` lists.
export function withDiff(cell) {
  const dir = buildRepo({ history: cell.history, issue: cell.issue, extraFiles: cell.extraFiles });
  try {
    const diff = threeDotDiff(dir, cell.baseBranch, cell.head);
    const names = threeDotNames(dir, cell.baseBranch, cell.head);
    if (!diff.trim()) throw new Error(`${cell.id}: empty diff ${cell.baseBranch}...${cell.head}`);
    return { extraFiles: { ...cell.extraFiles, [`.github-cache/diff-${cell.spec.pr}.patch`]: diff.replace(/\n$/, '') }, names };
  } finally { rmSync(dir, { recursive: true, force: true }); }
}

export function buildCases() {
  return cells.map((c) => {
    const { extraFiles, names } = withDiff(c);
    if (c.spec.changedFiles.length) {
      const a = [...c.spec.changedFiles].sort().join(','), b = [...names].sort().join(',');
      if (a !== b) throw new Error(`${c.id}: changedFiles ${a} != diff ${b}`);
    }
    const scripts = Object.fromEntries(Object.entries(controlsFor(c)).map(([k, lines]) => [k, lines.join('\n')]));
    return {
      id: c.id, pattern: 'convention-adherence', kind: 'contract', trials: 1,
      params: {
        repo: REPO,
        request: c.request,
        issue: c.issue,
        history: c.history,
        extra_files: extraFiles,
        expect: { task: { name: 'verdict', check: verdictCheck(c), tristate: true }, conventions: [] },
        scripts,
        script_expect: Object.fromEntries(CONTROL_NAMES.map((k) => [k, expectedOutcome(k, c)])),
      },
    };
  });
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('gen.mjs')) {
  const cases = buildCases();
  const suite = {
    name: 'qm-heldout',
    subject: { path: '../../subjects/dev-structure/M' },
    repo_root: '../..',
    model: 'claude-sonnet-5-5',
    arms: CONTROL_NAMES.map((s) => `script:${s}`),
    compare: { baseline: 'script:null', candidates: ['script:reference'] },
    cases,
  };
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `# Generated by experiments/qm-heldout/gen.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
  const here = new URL('.', import.meta.url);
  writeFileSync(new URL('process-spec.json', here), `${JSON.stringify(Object.fromEntries(cells.map((c) => [c.id, c.spec])), null, 1)}\n`);
  writeFileSync(new URL('verdicts.json', here), `${JSON.stringify(cells.map((c) => ({
    case: c.id, type: c.type, lane: c.lane, pr: c.spec.pr, verdict: c.expect.verdict,
    ...(c.expect.route ? { route: c.expect.route.label } : {}), ...(c.expect.approver ? { approver: c.expect.approver } : {}), ...(c.expect.answer ? { answers: `the fact about #${c.expect.answer}` } : {}),
    harmIfWrong: c.expect.verdict === 'pass' ? ['overBlock', ...(c.spec.decisionWords.length ? ['answeredQuestion'] : [])] : [c.expect.harm, ...(c.spec.decisionWords.length && c.expect.harm !== 'answeredQuestion' ? ['answeredQuestion'] : [])],
    reason: c.expect.reason,
  })), null, 1)}\n`);
  console.log(`wrote ${out} (${cases.length} cases), experiments/qm-heldout/process-spec.json, experiments/qm-heldout/verdicts.json`);
}
