// Build a rule-content variant of the default skill (EXP-25): apply the replacements in a
// candidate file to the design doc, build the MskillG arm from the patched text, and check that
// the only lines that differ from MskillG come from the replacements.
// The candidate file holds a fenced ```json block: [{ "old": "...", "new": "..." }, ...].
// Each `old` must occur exactly once in the design doc.
// Usage: node experiments/structure/build-variant.mjs <candidate.md> <ArmName> [design.md] [outRoot]
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { build, parse } from './build-arms.mjs';

// The base arm defaults to MskillG; `--base <Arm>` (last two arguments) builds on another arm of
// build-arms.mjs, e.g. MskillD1 (EXP-27).
const argv = process.argv.slice(2);
const bi = argv.indexOf('--base');
const baseArm = bi === -1 ? 'MskillG' : argv[bi + 1];
if (bi !== -1) argv.splice(bi, 2);
const [cand, name, src = 'docs/planning/11-dev-role-design.md', outRoot = 'subjects/dev-structure'] = argv;
if (!cand || !name) { console.error('usage: build-variant.mjs <candidate.md> <ArmName>'); process.exit(1); }
const block = readFileSync(cand, 'utf8').replace(/\r\n/g, '\n').match(/```json\n([\s\S]*?)\n```/);
if (!block) throw new Error(`${cand}: no json block`);
const reps = JSON.parse(block[1]);
let text = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
for (const r of reps) {
  const n = text.split(r.old).length - 1;
  if (n !== 1) throw new Error(`old text occurs ${n} times (must be 1): ${r.old.slice(0, 60)}`);
  text = text.split(r.old).join(r.new);
}
const base = build(parse(readFileSync(src, 'utf8')))[baseArm];
const variant = build(parse(text))[baseArm];

// Check: same files; every differing line is part of a replacement's new text, and every line
// that disappeared is part of a replacement's old text.
const newLines = new Set(reps.flatMap((r) => r.new.split('\n').map((l) => l.trim()).filter(Boolean)));
const oldLines = new Set(reps.flatMap((r) => r.old.split('\n').map((l) => l.trim()).filter(Boolean)));
let bad = 0, changed = 0;
if (JSON.stringify(Object.keys(base).sort()) !== JSON.stringify(Object.keys(variant).sort())) { console.log('file sets differ'); bad++; }
for (const f of Object.keys(base)) {
  const a = base[f].split('\n').map((l) => l.trim()), b = (variant[f] ?? '').split('\n').map((l) => l.trim());
  const inA = new Set(a), inB = new Set(b);
  for (const l of b.filter((l) => l && !inA.has(l))) { changed++; if (![...newLines].some((n) => l.includes(n) || n.includes(l))) { console.log(`  unexpected new line in ${f}: ${l.slice(0, 80)}`); bad++; } }
  for (const l of a.filter((l) => l && !inB.has(l))) { if (![...oldLines].some((o) => l.includes(o) || o.includes(l))) { console.log(`  unexpected removed line in ${f}: ${l.slice(0, 80)}`); bad++; } }
}
if (!changed) { console.log('no line changed'); bad++; }
const dir = join(outRoot, name);
rmSync(dir, { recursive: true, force: true });
for (const [rel, body] of Object.entries(variant)) { mkdirSync(dirname(join(dir, rel)), { recursive: true }); writeFileSync(join(dir, rel), body); }
writeFileSync(join(dir, 'SOURCE.md'), `Generated by experiments/structure/build-variant.mjs from ${src} with the replacements in ${cand}. Do not edit by hand.\n`);
console.log(`${name}: ${reps.length} replacement(s), ${changed} changed line(s) -> ${bad ? `FAIL (${bad})` : `OK: only the replaced rule text differs from ${baseArm}`}`);
process.exit(bad ? 1 : 0);
