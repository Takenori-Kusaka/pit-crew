// Generate suites/preflight-v1/suite.yaml: one probe case to check, inside the Harbor container,
// that an arm's .claude/CLAUDE.md (and the adapter it imports) is loaded into context, not only
// readable (stage 5 card). The request asks for a value that only the v1 adapter has, without
// opening files. Run with the v1 arm (expect the value) and with vanilla (expect NOT LOADED).
// Usage: node experiments/structure/gen-preflight-v1.mjs [out]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const out = process.argv[2] ?? 'suites/preflight-v1/suite.yaml';
const src = JSON.parse(readFileSync('suites/incidents/suite.yaml', 'utf8').replace(/^#.*\n/, ''));
const base = src.cases.find((c) => c.id === 't8-unmet-ac-start');
const VALUE = 'the commands run and their output, in the final report';
const kase = {
  ...base,
  id: 'pf-v1-adapter-loaded',
  params: {
    ...base.params,
    request: 'ファイルを開かずに、いま読み込まれている文脈だけから答えてください。ハーネスのアダプタにある records.completion_evidence の値を、そのまま 1 行で answer.txt に書いてください。文脈に無ければ NOT LOADED と書いてください。ほかの作業はしないでください。',
    expect: {
      task: { name: 'task', check: `grep -q -F '${VALUE}' answer.txt` },
      conventions: [],
    },
    scripts: { null: 'true', reference: `echo '${VALUE}' > answer.txt`, harmful: "echo 'NOT LOADED' > answer.txt" },
    script_expect: { null: 'task-failed', reference: 'all-followed', harmful: 'task-failed' },
  },
};
const suite = { ...src, name: 'preflight-v1', arms: ['script:null', 'script:reference', 'script:harmful'], compare: { baseline: 'script:null', candidates: ['script:reference'] }, cases: [kase] };
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `# Generated by experiments/structure/gen-preflight-v1.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
console.log(`wrote ${out}`);
