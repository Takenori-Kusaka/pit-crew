// Generate suites/subject2/suite.yaml: s2-1 (cells.mjs) and the single-key cells s2-k1 / s2-k5
// (cells5.mjs), s2-k3b / s2-k4b (cells6.mjs) and s2-k2c (cells7.mjs; owner decision 2026-11-04: one
// adapter key per cell). The re-derivation discarded s2-2 … s2-13, s2-k2 … s2-k4 and s2-k2b; they are not in the suite and are not fixed (s2-2 … s2-4
// stay in cells.mjs only because s2-1 shares its fixture code with them).
// Each cell is a convention-adherence case: `task` is the substance, the other check is the
// cell's adapter key (s2-1 checks several; names in adapter-check.mjs ADAPTER_KEYS).
// Output is JSON, which is valid YAML. Usage: node experiments/subject2/gen-subject2.mjs [out]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { cells, keyCheck, REPO } from './cells.mjs';
import { cells5, expect5, keyCheck5, taskCheck5 } from './cells5.mjs';
import { cells6, keyCheck6, taskCheck6 } from './cells6.mjs';
import { cells7, keyCheck7, taskCheck7 } from './cells7.mjs';

const out = process.argv[2] ?? 'suites/subject2/suite.yaml';
const cases = cells.filter((c) => c.id === 's2-1').map((c) => ({
  id: c.id, pattern: 'convention-adherence', kind: 'contract', trials: 1,
  params: {
    repo: REPO,
    request: c.request,
    issue: c.issue,
    history: c.history,
    expect: {
      task: { name: 'task', check: c.task },
      conventions: Object.keys(c.keys).map((k) => ({ name: k, check: keyCheck(c, k) })),
    },
    scripts: { null: 'true', ...c.scripts },
    script_expect: { null: 'task-failed', reference: 'all-followed', generic: 'some-followed', harmful: 'task-failed' },
  },
}));
for (const [c, keyCheck, taskCheck] of [...cells5.map((c) => [c, keyCheck5, taskCheck5]), ...cells6.map((c) => [c, keyCheck6, taskCheck6]), ...cells7.map((c) => [c, keyCheck7, taskCheck7])]) cases.push({
  id: c.id, pattern: 'convention-adherence', kind: 'contract', trials: 1,
  params: {
    repo: REPO,
    request: c.request,
    issue: c.issue,
    history: c.history,
    expect: {
      task: { name: 'task', check: taskCheck(c), ...(c.taskTristate ? { tristate: true } : {}) },
      conventions: [{ name: c.key, check: keyCheck(c), ...(c.tristate ? { tristate: true } : {}) }],
    },
    scripts: { null: 'true', ...c.scripts },
    script_expect: expect5(c),
  },
});
const arms = [...new Set(cases.flatMap((c) => Object.keys(c.params.scripts)))].map((s) => `script:${s}`);
const suite = {
  name: 'subject2',
  subject: { path: '../../subjects/dev-structure/M' },
  repo_root: '../..',
  model: 'claude-sonnet-5-5',
  arms,
  compare: { baseline: 'script:null', candidates: ['script:reference'] },
  cases,
};
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `# Generated by experiments/subject2/gen-subject2.mjs. Do not edit by hand.\n${JSON.stringify(suite, null, 1)}\n`);
console.log(`wrote ${out}`);
